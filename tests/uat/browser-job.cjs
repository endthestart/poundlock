// Isolated controller only. Completion below is a runner protocol fixture, not model evidence.
const {chromium}=require('playwright');
const fs=require('node:fs/promises');
const assert=require('node:assert/strict');
(async()=>{
  const base=process.env.UAT_BASE;
  assert.match(base||'',/^http:\/\/127\.0\.0\.1:\d+$/,'Use an isolated loopback controller');
  const directory=process.env.UAT_DATA;
  const token=(await fs.readFile(`${directory}/data/admin-token`,'utf8')).trim();
  const runner=(await fs.readFile(`${directory}/runtime/runner-token`,'utf8')).trim();
  const browser=await chromium.launch({headless:true});
  try {
    const page=await browser.newPage({viewport:{width:1440,height:1100}});
    const errors=[];page.on('pageerror',error=>errors.push(error.message));
    const request=async(method,path,data,credential=token)=>{
      const response=await page.request.fetch(base+path,{method,data,headers:{authorization:`Bearer ${credential}`}});
      assert.ok(response.ok(),`${method} ${path}: ${response.status()} ${await response.text()}`);
      return response.json();
    };
    const endpoint=await request('POST','/api/v1/endpoints',{name:'UI fixture',kind:'openai',base_url:process.env.UAT_MODEL_BASE||'http://127.0.0.1:17333/v1',api_key:''});
    await request('POST','/api/v1/model-profiles',{name:'UI fixture coding',endpoint_id:endpoint.id,model_id:'fixture',context_tokens:8192,max_output_tokens:1024,workload_class:'durable-coding-agent',wake_policy:'never',data_destination:'operator_network'});
    const issued=await request('POST','/api/v1/api-tokens',{name:'UI fixture jobs',permissions:['jobs:read','jobs:submit','jobs:cancel']});
    await page.goto(base);await page.locator('#token').fill(issued.token);await page.getByRole('button',{name:'Unlock',exact:true}).click();
    await page.locator('#application').waitFor({state:'visible'});
    assert.equal(await page.getByRole('button',{name:'Setup',exact:true}).isVisible(),false);
    await fs.mkdir(`${directory}/fixture/src`,{recursive:true});
    await fs.mkdir(`${directory}/fixture/.git`,{recursive:true});
    await fs.writeFile(`${directory}/fixture/src/file.txt`,'uncommitted baseline\n');
    await fs.writeFile(`${directory}/fixture/.env`,'DO_NOT_UPLOAD=private');
    await fs.writeFile(`${directory}/fixture/.git/config`,'DO_NOT_UPLOAD=git');
    await page.locator('#job-folder').setInputFiles(`${directory}/fixture`);
    assert.match(await page.locator('#job-file-summary').textContent(),/1 files selected.*1 unchecked/);
    assert.equal(await page.locator('#job-files').getByText('.git/config',{exact:false}).count(),0);
    await page.locator('#job-prompt').fill('Update the supplied file (browser fixture)');
    await page.locator('#job-checks summary').click();
    await page.locator('#job-commands').fill('node --test');
    await page.locator('#job-protected').fill('tests');
    await page.locator('#job-repairs').fill('1');
    assert.equal(await page.locator('#job-network').isDisabled(),true);
    let submissions=[];
    await page.route('**/api/v1/jobs',async route=>{
      if(route.request().method()!=='POST')return route.continue();
      submissions.push(route.request().postDataJSON());
      const response=await route.fetch();
      if(submissions.length===1)return route.abort('failed');
      return route.fulfill({response});
    });
    await page.locator('#job-form button[type="submit"], #job-form button:not([type])').click();
    await page.waitForFunction(()=>document.querySelector('#toast').classList.contains('error'));
    await page.locator('#job-form button[type="submit"], #job-form button:not([type])').click();
    await page.locator('#job-detail').waitFor({state:'visible'});
    assert.equal(submissions.length,2);assert.deepEqual(submissions[0],submissions[1]);
    assert.equal(submissions[0].policy.max_repairs,1);assert.equal(submissions[0].policy.verification.commands[0].command,'node --test');
    assert.equal(submissions[0].policy.network,'inference_only');
    assert.equal(submissions[0].project_id,undefined);assert.equal(submissions[0].source.files.length,1);
    assert.equal(Buffer.from(submissions[0].source.files[0].content_base64,'base64').toString(),'uncommitted baseline\n');
    const jobs=await request('GET','/api/v1/jobs',undefined,issued.token);assert.equal(jobs.length,1);
    let claimed;
    for(let i=0;i<30&&!claimed;i++){claimed=await request('POST','/runner/v1/claim',{},runner);if(!claimed)await page.waitForTimeout(500)}
    assert.ok(claimed,'scheduler must make job claimable');
    const source=await request('GET',`/runner/v1/jobs/${claimed.job.id}/source`,undefined,runner);
    assert.equal(source.files[0].path,'src/file.txt');
    const patch='diff --git a/src/file.txt b/src/file.txt\n--- a/src/file.txt\n+++ b/src/file.txt\n@@ -1 +1 @@\n-uncommitted baseline\n+<img src=x onerror="window.patchExecuted=true">\n';
    await request('POST',`/runner/v1/jobs/${claimed.job.id}/complete`,{patches:[{root:'workspace',base_revision:'a'.repeat(40),patch}],output:'Protocol fixture output — no model was run.',provenance:{verification:{status:'passed',reason:'All verification commands passed.',commands:[{command:'node --test',exit_code:0,duration_ms:'<img src=x onerror="window.metadataExecuted=true">',output:'1 test passed',truncated:false}]},source:claimed.source,previous_attempts:[{number:'1" onmouseover="window.metadataExecuted=true',patches:[{root:'workspace',base_revision:'a'.repeat(40),patch:'earlier failed patch\n'}],output:'earlier output',verification:{status:'failed',reason:'A command failed.'}}]},cleanup:{containers_removed:true,attempt_directory_removed:true}},runner);
    await page.reload();
    await page.locator('[data-job]').focus();
    await page.keyboard.press('Enter');
    await page.locator('.result-summary').getByText('Checks passed',{exact:true}).waitFor();
    await page.locator('#job-list .badge.passed',{hasText:'Checks passed'}).first().waitFor();
    assert.equal(await page.locator('pre').filter({hasText:'Protocol fixture output — no model was run.'}).isVisible(),false,'agent logs should start collapsed');
    await page.locator('#job-detail>details>summary').filter({hasText:/^Agent output$/}).click();
    await page.getByText('Protocol fixture output — no model was run.',{exact:true}).waitFor();
    assert.equal(await page.evaluate(()=>window.patchExecuted||window.metadataExecuted),undefined,'result markup executed');
    assert.equal(await page.locator('#job-detail [onmouseover], #job-detail img').count(),0,'unescaped provenance markup');
    const pendingDownload=page.waitForEvent('download');await page.getByRole('button',{name:'Download patch',exact:true}).first().click();
    const downloaded=await pendingDownload;await downloaded.saveAs(`${directory}/download.patch`);
    assert.equal(await fs.readFile(`${directory}/download.patch`,'utf8'),patch);
    await page.getByText('Earlier attempts (1)',{exact:true}).click();
    await page.getByText('earlier failed patch',{exact:true}).waitFor();
    await page.evaluate(()=>window.scrollTo(0,0));
    await page.screenshot({path:`${directory}/desktop.png`,fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.evaluate(()=>window.scrollTo(0,0));
    await page.screenshot({path:`${directory}/mobile.png`,fullPage:true});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'mobile overflow');
    await page.locator('#job-source').selectOption('git');
    assert.equal(await page.locator('#job-upload').isVisible(),false);
    assert.equal(await page.locator('#job-git').isVisible(),true);
    await page.locator('#job-git-url').fill('https://github.com/owner/repository.git');
    await page.locator('#job-git-revision').fill('main');
    await page.locator('#job-prompt').fill('Pinned Git browser fixture');
    await page.getByRole('button',{name:'Submit job',exact:true}).click();
    assert.equal(submissions.length,2,'A mutable ref must fail browser validation');
    await page.locator('#job-git-revision').fill('a'.repeat(40));
    const gitAccepted=page.waitForResponse(r=>r.url().endsWith('/api/v1/jobs')&&r.request().method()==='POST');
    await page.getByRole('button',{name:'Submit job',exact:true}).click();
    const gitJob=await (await gitAccepted).json();
    assert.equal(submissions[2].source.kind,'git');
    assert.equal(submissions[2].source.revision,'a'.repeat(40));
    await request('POST',`/api/v1/jobs/${gitJob.id}/cancel`,{},issued.token);
    assert.deepEqual(errors,[]);
    console.log('PASS: jobs-only login, folder review/exclusions, immutable retry after lost response, one accepted job, runner source fetch, result after reload, verification controls, authenticated patch download, escaped patch markup, earlier attempts, responsive layout, pinned Git form and mutable-ref rejection');
  }finally{await browser.close()}
})().catch(error=>{console.error(error);process.exitCode=1});
